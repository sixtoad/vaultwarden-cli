//! The shared signer-admission vectors (shared-approval-checks-spec S-2):
//! one list of cases, built here from the provider's golden vector and the
//! rule each case states, checked against the Rust reference
//! (`provider::admission::admits`) and committed as
//! `companion/fixtures/approval-v2-admission.json`, which the macOS/iOS
//! (`ProductionTranscript.admits`) and Android (`ApprovalTranscript.admits`)
//! native guards must answer identically. Regenerate the file with
//! `UPDATE_ADMISSION_VECTORS=1 cargo test --test admission_vectors`.
use companion_core::provider::admission::{admits, Binding, Purpose};
use companion_core::provider::approval_v2 as v2;
use serde_json::{json, Value};
use std::path::Path;

#[path = "support/admission_cases.rs"]
mod support;
use support::{cases, golden, Case};

const VECTORS: &str = "../fixtures/approval-v2-admission.json";

fn document(cases: &[Case]) -> Value {
    let rows: Vec<Value> = cases
        .iter()
        .map(
            |(name, purpose, provider, client, key, transcript, admitted)| {
                json!({"name": name, "purpose": purpose, "provider_identity": provider,
                   "approval_client": client, "public_key_hex": v2::hex(key),
                   "transcript_hex": v2::hex(transcript), "admitted": admitted})
            },
        )
        .collect();
    json!({
        "_contract": "Generated by companion/rust/tests/admission_vectors.rs from tests/fixtures/approval-v2-golden.json. Every native signer guard (ProductionTranscript.admits, ApprovalTranscript.admits) must return `admitted` for (transcript, purpose, binding, public key). Do not edit by hand: UPDATE_ADMISSION_VECTORS=1 cargo test --test admission_vectors.",
        "cases": rows,
    })
}

#[test]
fn every_case_matches_the_rust_reference_and_the_committed_vectors() {
    let cases = cases(&golden());
    for (name, purpose, provider, client, key, transcript, admitted) in &cases {
        let binding = Binding::parse(provider, client).unwrap();
        let purpose = Purpose::parse(purpose).unwrap();
        assert_eq!(
            admits(transcript, purpose, &binding, key),
            *admitted,
            "{name}"
        );
    }
    let text = serde_json::to_string_pretty(&document(&cases)).unwrap() + "\n";
    let path = Path::new(env!("CARGO_MANIFEST_DIR")).join(VECTORS);
    if std::env::var_os("UPDATE_ADMISSION_VECTORS").is_some() {
        std::fs::write(&path, &text).unwrap();
    }
    // Compared as JSON values: a Windows checkout may turn the file's line
    // endings into CRLF, which changes the text but not the vectors.
    let committed = std::fs::read_to_string(&path).unwrap_or_default();
    let committed: Option<Value> = serde_json::from_str(&committed).ok();
    assert!(
        committed.as_ref() == Some(&document(&cases)),
        "{VECTORS} is stale: regenerate it"
    );
}
